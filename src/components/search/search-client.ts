interface PagefindSubResult {
	title: string;
	url: string;
	excerpt: string;
}

interface PagefindResultData {
	url: string;
	excerpt: string;
	meta: Record<string, string | undefined>;
	sub_results: PagefindSubResult[];
}

interface PagefindSearch {
	results: { id: string; data: () => Promise<PagefindResultData> }[];
}

interface Pagefind {
	init: () => Promise<void>;
	debouncedSearch: (
		query: string,
		options?: object,
		timeout?: number
	) => Promise<PagefindSearch | null>;
}

const MAX_RESULTS = 20;
const MAX_SUB_RESULTS = 3;

/** Pagefind indexes `foo.html`; the site serves it at `/foo`. */
export function cleanUrl(url: string): string {
	return url.replace(/\.html(?=#|$)/, '').replace(/\/index(?=#|$)/, '') || '/';
}

/**
 * Pagefind excerpts are HTML-escaped text with `<mark>` highlights. Rebuild
 * them from text nodes and `<mark>` elements only, so nothing else can be injected.
 */
function excerptFragment(excerpt: string): DocumentFragment {
	const parsed = new DOMParser().parseFromString(`<p>${excerpt}</p>`, 'text/html');
	const fragment = document.createDocumentFragment();
	for (const node of parsed.body.firstElementChild?.childNodes ?? []) {
		if (node.nodeType === Node.TEXT_NODE) {
			fragment.append(node.textContent ?? '');
		} else if (node instanceof HTMLElement && node.tagName === 'MARK') {
			const mark = document.createElement('mark');
			mark.textContent = node.textContent;
			fragment.append(mark);
		} else {
			fragment.append(node.textContent ?? '');
		}
	}
	return fragment;
}

function element<K extends keyof HTMLElementTagNameMap>(
	tag: K,
	className?: string,
	text?: string
): HTMLElementTagNameMap[K] {
	const node = document.createElement(tag);
	if (className) node.className = className;
	if (text !== undefined) node.textContent = text;
	return node;
}

function renderResult(data: PagefindResultData): HTMLLIElement {
	const item = element('li', 'border-border rounded-lg border p-5');
	const heading = element('h2', 'text-lg font-semibold leading-snug');
	const link = element('a', 'search-result-link text-text hover:text-accent no-underline');
	link.href = cleanUrl(data.url);
	link.textContent = data.meta['title'] ?? cleanUrl(data.url);
	heading.append(link);
	item.append(heading);

	const details = [data.meta['category'], data.meta['date']].filter(Boolean).join(' · ');
	if (details) item.append(element('p', 'text-muted mt-1 text-sm', details));

	const excerpt = element('p', 'text-muted mt-2');
	excerpt.append(excerptFragment(data.excerpt));
	item.append(excerpt);

	const sections = data.sub_results
		.filter((sub) => cleanUrl(sub.url) !== cleanUrl(data.url) && sub.title !== data.meta['title'])
		.slice(0, MAX_SUB_RESULTS);
	if (sections.length > 0) {
		const list = element('ul', 'border-border mt-3 flex flex-col gap-2 border-l pl-4 text-sm');
		list.setAttribute('aria-label', `Matching sections in ${link.textContent}`);
		for (const sub of sections) {
			const entry = element('li');
			const subLink = element('a', 'search-result-link font-medium');
			subLink.href = cleanUrl(sub.url);
			subLink.textContent = sub.title;
			const subExcerpt = element('p', 'text-muted');
			subExcerpt.append(excerptFragment(sub.excerpt));
			entry.append(subLink, subExcerpt);
			list.append(entry);
		}
		item.append(list);
	}
	return item;
}

export function initSearch(root: HTMLElement): void {
	const form = root.querySelector<HTMLFormElement>('form[data-search-form]');
	const input = root.querySelector<HTMLInputElement>('input[name="q"]');
	const status = root.querySelector<HTMLElement>('[data-search-status]');
	const results = root.querySelector<HTMLOListElement>('[data-search-results]');
	if (!form || !input || !status || !results) return;

	let pagefind: Pagefind | undefined;
	let latestQuery = '';

	async function load(): Promise<Pagefind | undefined> {
		if (pagefind) return pagefind;
		try {
			const url = '/pagefind/pagefind.js';
			pagefind = (await import(/* @vite-ignore */ url)) as Pagefind;
			await pagefind.init();
			return pagefind;
		} catch {
			status!.textContent =
				'The search index is not available. It is generated by the production build (npm run build), so search does not work on the dev server.';
			return undefined;
		}
	}

	async function run(query: string): Promise<void> {
		latestQuery = query;
		const url = new URL(window.location.href);
		if (query) url.searchParams.set('q', query);
		else url.searchParams.delete('q');
		window.history.replaceState(null, '', url);

		if (!query) {
			results!.replaceChildren();
			status!.textContent = 'Type to search all published articles.';
			return;
		}

		const engine = await load();
		if (!engine) return;
		const search = await engine.debouncedSearch(query, {}, 200);
		if (search === null || query !== latestQuery) return;

		const data = await Promise.all(search.results.slice(0, MAX_RESULTS).map((r) => r.data()));
		if (query !== latestQuery) return;

		results!.replaceChildren(...data.map(renderResult));
		const count = search.results.length;
		status!.textContent =
			count === 0
				? `No articles match “${query}”.`
				: `${count} ${count === 1 ? 'article matches' : 'articles match'} “${query}”${count > MAX_RESULTS ? ` (showing the first ${MAX_RESULTS})` : ''}.`;
	}

	form.addEventListener('submit', (event) => {
		event.preventDefault();
		void run(input.value.trim());
	});
	input.addEventListener('input', () => void run(input.value.trim()));

	// Arrow keys move between the field and result links.
	root.addEventListener('keydown', (event) => {
		if (event.key !== 'ArrowDown' && event.key !== 'ArrowUp') return;
		const links = [...results.querySelectorAll<HTMLAnchorElement>('a.search-result-link')];
		if (links.length === 0) return;
		const active = document.activeElement;
		const index = links.findIndex((link) => link === active);
		if (active === input && event.key === 'ArrowDown') {
			event.preventDefault();
			links[0]?.focus();
		} else if (index !== -1) {
			event.preventDefault();
			const next = event.key === 'ArrowDown' ? index + 1 : index - 1;
			if (next < 0) input.focus();
			else links[Math.min(next, links.length - 1)]?.focus();
		}
	});

	const initial = new URL(window.location.href).searchParams.get('q')?.trim() ?? '';
	input.value = initial;
	void run(initial);
}
